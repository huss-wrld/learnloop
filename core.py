# Hermes wraps a skill invocation in one of two formats (agent/skill_commands.py, v0.23.0+):
#   single:  '[IMPORTANT: The user has invoked the "learnloop:study" skill, indicating ...' + body + TOPIC_LEAD + topic
#   stacked: '[IMPORTANT: The user has invoked the "..." stacked skill bundle, ...' + 'User instruction: topic' + bodies
# Desktop produced the stacked one for a plain "/learnloop:study <topic>" (10 Nov), so both must start a lesson.
# Our own skill body's heading identifies which skill; the scaffold prefix keeps a pasted heading from counting.
SCAFFOLD = "[IMPORTANT: The user has invoked the "
STUDY_HEADING = "# learnloop lesson: start"
PRACTICE_HEADING = "# learnloop practice: start"


def _invocation(message: str, marker: str, heading: str) -> str | None:
    message = message or ""
    if SCAFFOLD not in message[:300]:
        return None
    if marker in message:
        _, found, topic = message.rpartition(TOPIC_LEAD)
        return topic.strip() if found else ""
    if heading not in message:
        return None
    header = message.split("\n\n---\n", 1)[0].split("\n\n[Loaded as part of", 1)[0]
    found = re.search(r"^User instruction: (.+)$", header, re.M)
    return found.group(1).strip() if found else ""


# Messages Hermes injects as user turns (background delegation results, process notifications, reloads):
# never the learner's answer or thinking. Shapes from gateway/run_notifications.py and gateway/run.py (v0.23.0).
NOTIFICATION_FOOTER = "[INTERNAL NOTIFICATION — generated by the Hermes gateway"


def is_background_message(message: str) -> bool:
    m = (message or "").lstrip()
    if NOTIFICATION_FOOTER in m:
        return True
    return m.startswith("[IMPORTANT: ") and not m.startswith(SCAFFOLD)


BACKGROUND_NOTE = ("This message is not from the learner: Hermes delivered it (most likely a research brief you "
                   "dispatched with delegate_task). Weave what matters into the lesson (cite its sources; if it "
                   "contradicts something you said, correct yourself openly) or absorb it silently if it changes "
                   "nothing.")


def practice_invocation(message: str) -> str | None:
    """The topic if this user message is a /learnloop:practice invocation ('' if none given), else None."""
    return _invocation(message, PRACTICE_MARKER, PRACTICE_HEADING)


def pick_material(store: Store, topic: str) -> list[str]:
    """Proposition ids to practise for a topic: an exact fact name (the graph's "Practice this") centres on that
    fact; otherwise the best search hits. Either way their premises and conclusions come along."""
    exact = store._prop_id(key_of(topic))
    seeds = [exact] if exact else [h["id"] for h in store.search(topic, limit=6)]
    return store.neighbourhood(seeds, limit=MATERIAL_LIMIT) if seeds else []


def material_text(store: Store, lesson_id: str) -> str:
    m = store.material(lesson_id)
    if not m["propositions"]:
        return ("No facts in the learner's graph match this topic: it's a free-form session. Pose untagged problems "
                "(omit target) from the topic itself.")
    lines = ["Material (picked from the learner's graph):"]
    lines += [f"- [{p['id']}] {p['name']}: {p['statement']}" for p in m["propositions"]]
    if m["chains"]:
        lines.append("Reasoning chains among them:")
        lines += [f"- {' + '.join(c['premises'])} → {c['conclusion']}" for c in m["chains"]]
    return "\n".join(lines)


def skill_invocation(message: str) -> str | None:
    """The topic if this user message is a /learnloop:study invocation ('' if no topic given), else None.
    Only Hermes's fixed marker counts: a user merely naming the skill doesn't start anything."""
    return _invocation(message, SKILL_MARKER, STUDY_HEADING)


