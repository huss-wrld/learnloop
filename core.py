_TEX = [(r"\\[dt]?frac\{([^{}]*)\}\{([^{}]*)\}", r"\1/\2"), (r"\\sqrt\{([^{}]*)\}", r"√\1"), (r"\\sqrt\s*([A-Za-z0-9_]+)", r"√\1"), (r"\\cdot", "·"), (r"\\times", "×"),
        (r"\\le(q)?\b", "≤"), (r"\\ge(q)?\b", "≥"), (r"\\approx", "≈"), (r"\\pm", "±"), (r"\\infty", "∞"),
        (r"\\(mathrm|mathbf|text|operatorname)\{([^{}]*)\}", r"\2"), (r"\\([A-Za-z]+)", r"\1"),
        (r"\^\{?2\}?", "²"), (r"\^\{?3\}?", "³"), (r"[{}]", "")]


def clip_markdown(text: str, limit: int) -> str:
    """Shorten Markdown+LaTeX for a preview without cutting inside a formula or a word.

    A plain [:limit] cut can end inside `$...$`, which the renderer then shows as stray glyphs; this cuts at the
    last space before the limit, then drops an unclosed formula, then adds an ellipsis."""
    text = " ".join((text or "").split())
    if len(text) <= limit:
        return text
    cut = text[:limit]
    if " " in cut:
        cut = cut[:cut.rindex(" ")]
    if cut.count("$") % 2:
        cut = cut[:cut.rindex("$")].rstrip()
    return cut.rstrip(" ,;:.") + "…"


def plain_math(text: str) -> str:
    """Option text for the learner's own chat line: Desktop shows user messages as plain text, so `$d_k$`
    would appear with its dollar signs. Inline LaTeX becomes readable plain text ("√d_k", "d_k²")."""
    def conv(m):
        t = m.group(1)
        for pat, rep in _TEX:
            t = re.sub(pat, rep, t)
        return t.strip()
    return re.sub(r"\$\$?([^$]+?)\$\$?", conv, text)


def card_answer_line(q: dict) -> str:
    """The chat message a card sends after submitting: readable for the learner, a nudge for the model."""
    sub = q["submission"] or {}
    if sub.get("dont_know"):
        head = "I don't know"
    elif q["options"]:
        head = ", ".join(f"{LETTERS[i]}) {plain_math(q['options'][i])}" for i in sub.get("choices", []))
    else:
        head = sub.get("text", "")
    parts = [head[:600]]
    if sub.get("confidence") is not None:
        parts.append(f"confidence {sub['confidence']}%")
    if sub.get("thinking"):
        parts.append(f"thinking: {sub['thinking'][:400]}")
    return " · ".join(parts)


def question_show(q: dict, cards: bool) -> str:
    if cards:
        return f'::learnloop-question{{id="{q["id"]}"}}'
    lines = [f"**Question.** {q['prompt']}", ""]
    if q["options"]:
        lines += [f"{LETTERS[i]}) {opt}" for i, opt in enumerate(q["options"])]
        multi = len(q["correct"]) > 1
        lines += ["", f"Reply with the letter{'s' if multi else ''}"
                  f"{' (more than one is right)' if multi else ''}, "]
    else:
        lines += ["Reply with your answer in your own words, "]
    stops = "/".join(str(s) for s in CONFIDENCE_STOPS)
    lines[-1] += f"your confidence ({stops} %), and your thinking. Or say \"I don't know\"."
    return "\n".join(lines)


